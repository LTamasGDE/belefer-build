/// Ismert kereskedő vagy szolgáltató.
class MerchantEntry {
  const MerchantEntry(this.name, this.categoryId, this.keys);

  /// Megjelenített név (a tétel megnevezése lesz).
  final String name;
  final String categoryId;

  /// Felismerendő alakok; több szóból is állhat („burger king”).
  final List<String> keys;
}

/// Kulcsszó, ami kategóriára (és megnevezésre) utal.
class KeywordEntry {
  const KeywordEntry(this.key, this.categoryId, {this.title, this.weight = 5});

  final String key;
  final String categoryId;

  /// Megnevezés, ha a mondatból más nem adódik („tankoltam” → Tankolás).
  final String? title;

  /// Mennyire egyértelmű (3 = általános, 5 = szokásos, 7 = nagyon konkrét).
  final int weight;
}

